export function searchSymbols(query: string, category = "") {
  const words = query
    .normalize("NFKC")
    .toLowerCase()
    .trim()
    .split(/\s+/)
    .filter(Boolean);
  return engineeringSymbols.filter(
    (symbol) =>
      (!category || symbol.category === category) &&
      words.every((word) =>
        `${symbol.name} ${symbol.category}`.toLowerCase().includes(word),
      ),
  );
}
